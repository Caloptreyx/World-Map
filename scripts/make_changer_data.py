#!/usr/bin/env python3
"""Builds the data tables of src/changer.rs from MCA Selector's resources (MIT).

- src/data/heightmaps.tsv: which heightmaps every block counts for, per MCA Selector heightmap
  config (one column per config, keyed by the DataVersion it applies from), plus whether MCA
  Selector's block registry knows the block (unquoted names in ReplaceBlocks must be known).
- src/data/changer_registry.tsv: chunk statuses, biomes (name, legacy numeric id) and structures
  (name with the alternative names MCA Selector deletes along with it), for parsing change values.

Usage: python3 scripts/make_changer_data.py [mcaselector/src/main/resources/mapping]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPPING = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/mcaselector/src/main/resources/mapping")

# (first DataVersion, config file): the versions MCA Selector's Heightmap implementations load them for
ERAS = [
    (1484, "java_1_13/heightmaps_18w19a.json"),
    (1901, "java_1_14/heightmaps_18w43a.json"),
    (2200, "java_1_15/heightmaps_19w34a.json"),
    (2504, "java_1_16/heightmaps_20w06a.json"),
    (2681, "java_1_17/heightmaps_20w45a.json"),
    (2834, "java_1_18/heightmaps_21w37a.json"),
    (3080, "java_1_19/heightmaps_22w11a.json"),
    (3207, "java_1_20/heightmaps_23w12a.json"),
    (3940, "java_1_21/heightmaps_24w18a.json"),
    (4536, "java_1_21/heightmaps_25w32a.json"),
    (4764, "java_26/heightmaps_26.1-snapshot-1.json"),
    (4883, "java_26/heightmaps_26.2-snapshot-1.json"),
    (4998, "java_26/heightmaps_26.3-snapshot-1.json"),
    (5003, "java_26/heightmaps_26.3-snapshot-4.json"),
]
BITS = {"world_surface": 1, "ocean_floor": 2, "motion_blocking": 4, "leaves": 8, "light_blocking": 16}
DIGITS = "0123456789abcdefghijklmnopqrstuv"


def strip(name):
    return name[len("minecraft:") :] if name.startswith("minecraft:") else name


def heightmaps():
    configs = []
    previous_leaves = set()
    for _, path in ERAS:
        config = {key: set(map(strip, values)) for key, values in json.loads((MAPPING / path).read_text()).items()}
        # the 26.3 configs lost their "leaves" list (MCA Selector then treats nothing as leaves);
        # leaves did not change, so the previous list carries over
        if "leaves" not in config:
            config["leaves"] = previous_leaves
        previous_leaves = config["leaves"]
        configs.append(config)
    registry = set(json.loads((MAPPING / "registry/blocks.json").read_text()))
    names = set(registry)
    for config in configs:
        for values in config.values():
            names |= values

    lines = [
        "# Generated by scripts/make_changer_data.py from MCA Selector's heightmap configs (MIT).",
        "# block\tone base-32 digit per config (1 WORLD_SURFACE, 2 OCEAN_FLOOR, 4 MOTION_BLOCKING,"
        " 8 leaves, 16 LIGHT_BLOCKING)\tr when in MCA Selector's block registry",
        "eras\t" + "\t".join(str(version) for version, _ in ERAS),
    ]
    for name in sorted(names):
        digits = ""
        for config in configs:
            mask = sum(bit for key, bit in BITS.items() if name in config.get(key, ()))
            digits += DIGITS[mask]
        lines.append(f"{name}\t{digits}\t{'r' if name in registry else ''}".rstrip("\t"))
    (ROOT / "src/data/heightmaps.tsv").write_text("\n".join(lines) + "\n")


def has_upper(name):
    return any(c.isupper() for c in name)


def structures():
    """StructureRegistry.init: valid names and their alternatives."""
    valid = set()
    for structure in json.loads((MAPPING / "registry/structures.json").read_text()):
        for name in structure.get("alt", []) + [structure["name"]]:
            valid.add(name)
            if not has_upper(name):
                valid.add("minecraft:" + name)
    alts = {}
    for name in sorted(valid):
        alts.setdefault(name, set()).add(name)
        if has_upper(name):
            lower = name.lower()
            if lower in valid:
                alts[name].add(lower)
                alts.setdefault(lower, set()).add(name)
            if "minecraft:" + lower in valid:
                alts[name].add("minecraft:" + lower)
                alts.setdefault("minecraft:" + lower, set()).add(name)
        elif name.startswith("minecraft:"):
            alts[name].add(name[len("minecraft:") :])
        else:
            alts[name].add("minecraft:" + name)
    return alts


def registry():
    lines = [
        "# Generated by scripts/make_changer_data.py from MCA Selector's registries (MIT).",
        "# status\tname | biome\tname\tlegacy id or -\tv when a valid biome name | structure\tname\talternatives",
    ]
    for status in json.loads((MAPPING / "registry/status.json").read_text()):
        lines.append(f"status\t{status}")
    biomes = set(json.loads((MAPPING / "registry/biomes.json").read_text()))
    ids = json.loads((MAPPING / "registry/biome_name_to_id.json").read_text())
    for name in sorted(biomes | set(ids)):
        biome_id = ids.get(name)
        lines.append(f"biome\t{name}\t{'-' if biome_id is None else biome_id}\t{'v' if name in biomes else ''}".rstrip("\t"))
    for name, alternatives in sorted(structures().items()):
        lines.append(f"structure\t{name}\t{','.join(sorted(alternatives))}")
    (ROOT / "src/data/changer_registry.tsv").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    heightmaps()
    registry()
